/// Declares an ORM entity with automatic `Entity` trait implementation.
///
/// Every field type must implement [`FetchValue`] (used by `from_row`) and
/// `Clone + Into<sea_query::Value>` (used by `InsertBuilder::from_entity`,
/// which clones each field out of `&self` before converting it).
///
/// # Examples
///
/// ```ignore
/// use omnia_orm::entity;
///
/// entity! {
///     table = "posts",
///     pub struct Post {
///         pub id: i32,
///         pub title: String,
///     }
/// }
/// ```
#[macro_export]
macro_rules! entity {
    // Full form: columns + joins + struct (single code-generation arm)
    (
        table = $table:literal,
        columns = [$( ($col_table:literal, $col_name:literal, $col_field:literal) ),* $(,)?],
        joins = [$($join:expr),* $(,)?],
        $(#[$meta:meta])*
        pub struct $struct_name:ident {
            $(
                $(#[$field_meta:meta])*
                pub $field_name:ident : $field_type:ty
            ),* $(,)?
        }
    ) => {
        $(#[$meta])*
        /// Entity table row generated by [`entity!`].
        pub struct $struct_name {
            $(
                $(#[$field_meta])*
                pub $field_name : $field_type
            ),*
        }

        impl $crate::Entity for $struct_name {
            const TABLE: &'static str = $table;

            fn projection() -> &'static [&'static str] {
                &[ $( stringify!($field_name) ),* ]
            }

            fn joins() -> Vec<$crate::Join> {
                vec![$($join),*]
            }

            fn column_specs() -> Vec<(&'static str, &'static str, &'static str)> {
                vec![$( ($col_field, $col_table, $col_name) ),*]
            }

            fn from_row(row: &$crate::Row) -> $crate::anyhow::Result<Self> {
                Ok(Self {
                    $(
                        $field_name: <$field_type as $crate::FetchValue>::fetch(row, stringify!($field_name))?,
                    )*
                })
            }
        }

        impl $crate::EntityValues for $struct_name {
            fn __to_values(&self) -> Vec<(&'static str, $crate::__private::Value)> {
                vec![
                    $(
                        (stringify!($field_name), self.$field_name.clone().into()),
                    )*
                ]
            }
        }
    };

    // Joins only → forward with empty columns
    (
        table = $table:literal,
        joins = [$($join:expr),* $(,)?],
        $($rest:tt)*
    ) => {
        $crate::entity! {
            table = $table,
            columns = [],
            joins = [$($join),*],
            $($rest)*
        }
    };

    // Bare table → forward with empty columns and joins
    (
        table = $table:literal,
        $($rest:tt)*
    ) => {
        $crate::entity! {
            table = $table,
            columns = [],
            joins = [],
            $($rest)*
        }
    };
}
